Exercise _e(
  String id,
  String en,
  String de,
  String pl,
  List<Muscle> primary,
  List<Muscle> secondary,
  Equipment equipment,
) => Exercise(
  id: id,
  names: {'en': en, 'de': de, 'pl': pl},
  primary: primary,
  secondary: secondary,
  equipment: equipment,
);

final Map<String, Exercise> _byId = {for (final e in exerciseLibrary) e.id: e};

/// The exercise called [id], from the library or from [custom].
Exercise? exerciseById(String id, [List<Exercise> custom = const []]) {
  final known = _byId[id];
  if (known != null) return known;
  for (final e in custom) {
    if (e.id == id) return e;
  }
  return null;
}
